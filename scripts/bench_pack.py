#!/usr/bin/env python3
"""Packs the benchmark's scratch save and route into host/benchmark_data.h (committed; regenerate with this script).

  python -I scripts/bench_pack.py [--save build/fixtures/saves/unlock_all] [--route host/routes/bench_florio.txt] [--out host/benchmark_data.h]

The save is the 'unlock_all' test fixture (a game-written save past the tutorial with every course open, no photos). Its files are
about 1.6 GB on disk but only about 90 KB are not zeros, so the blob keeps only the non-zero 4 KB blocks (adjacent blocks joined) and
the host re-creates the files sparse. Stream layout (little endian): u32 files, then per file: u16 path length, path (forward
slashes, relative to the profile's save folder), u64 size, u32 runs, then per run: u64 offset, u32 length, bytes.
"""
import argparse
import os
import struct
import sys

B = 4096


def pack_save(root):
    out = bytearray()
    files = []
    for r, _, fs in os.walk(root):
        for f in fs:
            p = os.path.join(r, f)
            files.append((os.path.relpath(p, root).replace(os.sep, '/'), p))
    files.sort()
    out += struct.pack('<I', len(files))
    for rel, p in files:
        data = open(p, 'rb').read()
        runs = []
        for i in range(0, len(data), B):
            if any(data[i:i + B]):
                if runs and runs[-1][0] + len(runs[-1][1]) == i:
                    runs[-1][1] += data[i:i + B]
                else:
                    runs.append([i, bytearray(data[i:i + B])])
        rb = rel.encode()
        out += struct.pack('<H', len(rb)) + rb + struct.pack('<QI', len(data), len(runs))
        for off, d in runs:
            out += struct.pack('<QI', off, len(d)) + bytes(d)
    return bytes(out)


def c_bytes(name, b):
    lines = ['static const unsigned char %s[%d] = {' % (name, len(b))]
    for i in range(0, len(b), 32):
        lines.append(','.join(str(x) for x in b[i:i + 32]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--save', default='build/fixtures/saves/unlock_all')
    ap.add_argument('--route', default='host/routes/bench_florio.txt')
    ap.add_argument('--out', default='host/benchmark_data.h')
    a = ap.parse_args()
    uid = [d for d in os.listdir(a.save) if os.path.isdir(os.path.join(a.save, d))]
    if len(uid) != 1:
        sys.exit('expected one user folder in ' + a.save)
    blob = pack_save(a.save)
    route = open(a.route, 'rb').read().replace(b'\r\n', b'\n')
    with open(a.out, 'w', newline='\n') as f:
        f.write('// SPDX-License-Identifier: MIT\n'
                '// Generated by scripts/bench_pack.py from the unlock_all test save (non-zero blocks only) and host/routes/bench_florio.txt. Do not edit.\n'
                '#pragma once\n')
        f.write(c_bytes('kBenchSave', blob) + '\n')
        f.write(c_bytes('kBenchRoute', route + b'\0') + '\n')
    print('save blob %d bytes, route %d bytes -> %s' % (len(blob), len(route), a.out))


main()
