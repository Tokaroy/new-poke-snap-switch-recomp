#!/usr/bin/env python3
"""Packs the shader-preparation course routes into host/prep_routes_data.h (committed; regenerate with this script).

  python -I scripts/prep_pack.py [--routes builder/hdtex_routes] [--out host/prep_routes_data.h]

`SnapRecomp.exe --prepare-shaders` (host/shaderprep.cpp) plays one scripted ride per course, hidden, so the game records every graphics
pipeline it uses into the player's own shader cache. The routes are the HD-texture capture routes (builder/hdtex_routes/qa_<course>_e0.txt:
title, lab hub, Lental Map, course entry, one ride with shutter taps, photo select) cut after the photo-submit screen; the Florio route keeps
its tail (Auto photo select, evaluation, score) because the evaluation passes are the same for every course and one pass through them is
enough. Only route text is packed, no game data.
"""
import argparse
import os
import re
import sys

# route file key -> (name shown to the player, keep the evaluation tail)
COURSES = [
    ('florio', 'Florio Nature Park', True),
    ('beach', 'Blushing Beach', False),
    ('jungle', 'Founja Jungle', False),
    ('river', 'River', False),
    ('sands', 'Sands', False),
    ('volcano', 'Fireflow Volcano', False),
    ('badlands', 'Badlands', False),
    ('seafloor', 'Seafloor', False),
    ('reef', 'Reef', False),
    ('ruins', 'Ruins', False),
    ('snow', 'Snowfields', False),
    ('cave', 'Outaway Cave', False),
    ('forest', 'Elsewhere Forest', False),
    ('ssp', 'Secret Side Path', False),
]


def cut(text, keep_tail):
    lines = [l.rstrip('\r') for l in text.split('\n')]
    out = []
    for l in lines:
        if l.startswith('# hdtex capture pass'):
            continue
        out.append(l)
        if not keep_tail and l.startswith('wait ui=photo_submit:FolderSelect'):
            out.append('end @f120')
            break
    return '\n'.join(out).rstrip('\n') + '\n'


def c_str(name, s):
    body = s.replace('\\', '\\\\').replace('"', '\\"').split('\n')
    return 'static const char %s[] =\n%s;' % (name, '\n'.join('    "%s\\n"' % l for l in body[:-1]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--routes', default='builder/hdtex_routes')
    ap.add_argument('--out', default='host/prep_routes_data.h')
    a = ap.parse_args()
    parts = ['// Generated by scripts/prep_pack.py from builder/hdtex_routes (route text only). Do not edit.', '#pragma once', '']
    table = []
    for i, (key, label, tail) in enumerate(COURSES):
        p = os.path.join(a.routes, 'qa_%s_e0.txt' % key)
        if not os.path.isfile(p):
            sys.exit('missing route ' + p)
        text = cut(open(p, encoding='utf-8').read(), tail)
        if not re.search(r'^wait ride\b', text, re.M):
            sys.exit('route %s has no "wait ride" line' % p)
        parts.append(c_str('kPrepRoute%d' % i, text))
        table.append('    {"%s", "%s", kPrepRoute%d},' % (key, label, i))
    parts += ['', 'struct PrepCourse { const char* key; const char* name; const char* route; };', 'static const PrepCourse kPrepCourses[] = {'] + table + ['};', '']
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(parts))
    print('wrote %s: %d courses' % (a.out, len(COURSES)))


if __name__ == '__main__':
    main()
