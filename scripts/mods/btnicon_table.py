"""Button icon mod: build the sprite key table that the renderer embeds (analysis/mods/button_icons.md).

  python -I scripts/mods/btnicon_table.py <UI master folder of the extracted game> <spec.json> [out.h]

spec.json (kept local, it names game files): [{"path": "Scenes/x.drp/x-00001.nutexb", "role": "A", "mode": "plate"}, ...]
  role: the Switch button the sprite shows: A B X Y L R ZL ZR Plus Minus
  mode: "plate" = the whole sprite is the button picture (a letter in a disc or plate): the twin is our glyph alone
        "pill"  = an orange chevron with a lettered backdrop: the twin is the original with our glyph drawn over the backdrop
Output (runtime/nvn/nvn_btnicon_table.h) holds only FNV-1a keys of the texture data, roles and modes: no game data, no file names.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts' / 'mods'))
import btnicon_keys as bk  # noqa: E402

ROLES = ['A', 'B', 'X', 'Y', 'StickL', 'StickR', 'L', 'R', 'ZL', 'ZR', 'Plus', 'Minus', 'Left', 'Up', 'Right', 'Down']   # hle::input::Button order
MODES = ['plate', 'pill']


def main():
    folder = Path(sys.argv[1])
    spec = json.load(open(sys.argv[2]))
    out = Path(sys.argv[3]) if len(sys.argv) > 3 else ROOT / 'runtime' / 'nvn' / 'nvn_btnicon_table.h'
    rows = {}
    for e in spec:
        k, t = bk.key_of(folder / e['path'])
        role, mode = ROLES.index(e['role']), MODES.index(e['mode'])
        if k in rows and rows[k][:2] != (role, mode):
            raise SystemExit('key %016x has two roles' % k)
        rows[k] = (role, mode, t['w'], t['h'])
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by scripts/mods/btnicon_table.py: FNV-1a 64 keys of the game\'s Switch button sprites (a hash of the texture data) with the button',
             '// each one shows and how to replace it. Keys only; no game data. %d sprites.' % len(rows),
             '#pragma once',
             'struct BtnSprite { unsigned long long key; unsigned char role, mode; };   // role: hle::input::Button; mode: 0 plate, 1 pill',
             'static const BtnSprite kBtnSprites[] = {']
    for k in sorted(rows):
        r = rows[k]
        lines.append('  {0x%016xull, %d, %d},   // %s %s %dx%d' % (k, r[0], r[1], ROLES[r[0]], MODES[r[1]], r[2], r[3]))
    lines.append('};')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(out, len(rows), 'sprites')


if __name__ == '__main__':
    main()
