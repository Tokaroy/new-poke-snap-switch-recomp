"""Button icon mod: build the Xbox / PlayStation glyph atlas that the renderer embeds (analysis/mods/button_icons.md).

  python -I scripts/mods/make_button_icons.py <kenney-input-prompts folder> [out.h]

Input is Kenney's "Input Prompts" pack (CC0, https://kenney.nl/assets/input-prompts, version 1.5A); its "Xbox Series/Default" and
"PlayStation Series/Default" PNGs are 64x64. Output is runtime/nvn/nvn_btnicon_atlas.h: one RGBA PNG, 64x64 cells, row 0 = Xbox,
row 1 = PlayStation, columns in the order of GLYPHS below (the same order as enum Glyph in runtime/hle/btn_icons.h), as a C byte array.
Only CC0 art goes in; the game's own icons are never touched. Needs Pillow.
"""
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
CELL = 64

# (glyph name, xbox file, playstation file). Order = enum Glyph.
GLYPHS = [
    ('FaceBottom', 'xbox_button_color_a', 'playstation_button_color_cross'),
    ('FaceRight', 'xbox_button_color_b', 'playstation_button_color_circle'),
    ('FaceLeft', 'xbox_button_color_x', 'playstation_button_color_square'),
    ('FaceTop', 'xbox_button_color_y', 'playstation_button_color_triangle'),
    ('L1', 'xbox_lb', 'playstation_trigger_l1'),
    ('R1', 'xbox_rb', 'playstation_trigger_r1'),
    ('L2', 'xbox_lt', 'playstation_trigger_l2'),
    ('R2', 'xbox_rt', 'playstation_trigger_r2'),
    ('Menu', 'xbox_button_menu', 'playstation5_button_options'),
    ('View', 'xbox_button_view', 'playstation5_button_create'),
    ('DpadUp', 'xbox_dpad_up', 'playstation_dpad_up'),
    ('DpadDown', 'xbox_dpad_down', 'playstation_dpad_down'),
    ('DpadLeft', 'xbox_dpad_left', 'playstation_dpad_left'),
    ('DpadRight', 'xbox_dpad_right', 'playstation_dpad_right'),
    ('StickL', 'xbox_stick_l', 'playstation_stick_l'),
    ('StickR', 'xbox_stick_r', 'playstation_stick_r'),
    ('StickLPress', 'xbox_stick_l_press', 'playstation_stick_l_press'),
    ('StickRPress', 'xbox_stick_r_press', 'playstation_stick_r_press'),
    ('StickLUp', 'xbox_stick_l_up', 'playstation_stick_l_up'),
    ('StickLDown', 'xbox_stick_l_down', 'playstation_stick_l_down'),
    ('StickLLeft', 'xbox_stick_l_left', 'playstation_stick_l_left'),
    ('StickLRight', 'xbox_stick_l_right', 'playstation_stick_l_right'),
    ('StickRUp', 'xbox_stick_r_up', 'playstation_stick_r_up'),
    ('StickRDown', 'xbox_stick_r_down', 'playstation_stick_r_down'),
    ('StickRLeft', 'xbox_stick_r_left', 'playstation_stick_r_left'),
    ('StickRRight', 'xbox_stick_r_right', 'playstation_stick_r_right'),
]


def load(folder, name):
    im = Image.open(folder / (name + '.png')).convert('RGBA')
    if im.size != (CELL, CELL):
        im = im.resize((CELL, CELL), Image.LANCZOS)
    return im


def main():
    kenney = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'runtime' / 'nvn' / 'nvn_btnicon_atlas.h'
    xb, ps = kenney / 'Xbox Series' / 'Default', kenney / 'PlayStation Series' / 'Default'
    atlas = Image.new('RGBA', (CELL * len(GLYPHS), CELL * 2), (0, 0, 0, 0))
    for i, (_, x, p) in enumerate(GLYPHS):
        atlas.paste(load(xb, x), (i * CELL, 0))
        atlas.paste(load(ps, p), (i * CELL, CELL))
    buf = io.BytesIO()
    atlas.save(buf, 'PNG', optimize=True)
    data = buf.getvalue()
    lines = ['// SPDX-License-Identifier: CC0-1.0 (the art); generated by scripts/mods/make_button_icons.py from Kenney "Input Prompts" 1.5A (CC0, https://kenney.nl/assets/input-prompts).',
             '// %d glyphs x 2 rows (Xbox, PlayStation), 64x64 cells, one RGBA PNG.' % len(GLYPHS),
             '#pragma once',
             'static const unsigned char kAtlasPng[%d] = {' % len(data)]
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(out, len(data), 'bytes PNG;', len(GLYPHS), 'glyphs')


if __name__ == '__main__':
    main()
