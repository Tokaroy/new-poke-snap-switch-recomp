# Regenerates ../nvn_ocean_spv.h from the four compute shaders of the FFT ocean module (runtime/fx/ocean_fft/shaders), same flags as that module's build.bat.
# Run: tools/venv-recomp/Scripts/python.exe -I runtime/nvn/shaders/make_ocean_spv.py   (glslangValidator from tools/vulkan_sdk)
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
src = root / 'runtime' / 'fx' / 'ocean_fft' / 'shaders'
names = [('kOceanInit', 'spectrum_init.comp'), ('kOceanEvolve', 'evolve.comp'), ('kOceanIfft', 'ifft.comp'), ('kOceanOutput', 'output.comp')]


def build(f):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '--target-env', 'vulkan1.1', '-I' + str(src), str(src / f), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        return struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())


lines = ['// SPDX-License-Identifier: GPL-3.0-only', '// Additional linking permission: see runtime/fx/ocean_fft/LICENSE.',
         '// Generated by shaders/make_ocean_spv.py from runtime/fx/ocean_fft/shaders/*.comp. Our own code, no game data.', '#pragma once', '#include <cstdint>']
for n, f in names:
    lines.append('static const uint32_t %s[] = {' % n + ','.join(hex(x) for x in build(f)) + '};')
(here.parent / 'nvn_ocean_spv.h').write_text('\n'.join(lines) + '\n')
