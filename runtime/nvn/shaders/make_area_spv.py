# Regenerates ../nvn_area_spv.h from area.comp (glslangValidator from tools/vulkan_sdk). Run: python -I make_area_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_area_spv.py from shaders/area.comp (present area downscale). No game data.',
       '#pragma once', '#include <cstdint>', 'namespace nvn {']
with tempfile.TemporaryDirectory() as t:
    o = pathlib.Path(t) / 'o.spv'
    subprocess.run([str(g), '-V', str(here / 'area.comp'), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
    w = struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())
out.append('static const uint32_t kAreaCompSpv[] = {' + ','.join(hex(x) for x in w) + '};')
out.append('}  // namespace nvn')
(here.parent / 'nvn_area_spv.h').write_text('\n'.join(out) + '\n')
