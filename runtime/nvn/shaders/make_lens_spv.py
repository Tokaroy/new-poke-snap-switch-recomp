# Regenerates ../nvn_lens_spv.h from the lens_*.frag shaders (glslangValidator from tools/vulkan_sdk). Run: python -I make_lens_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
ITEMS = [('kLensFocusFrag', 'lens_focus.frag'), ('kLensPrepFrag', 'lens_dof_prep.frag'), ('kLensBlurFrag', 'lens_dof_blur.frag'),
         ('kLensCompFrag', 'lens_dof_comp.frag'), ('kLensMblurFrag', 'lens_mblur.frag')]


def words(src):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '-S', 'frag', str(here / src), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        return struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())


out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_lens_spv.py from ' + ', '.join(s for _, s in ITEMS) + '. Our own code, no game data.', '#pragma once', '#include <cstdint>']
for name, src in ITEMS:
    out.append('static const uint32_t %s[] = {' % name + ','.join(hex(x) for x in words(src)) + '};')
(here.parent / 'nvn_lens_spv.h').write_text('\n'.join(out) + '\n')
