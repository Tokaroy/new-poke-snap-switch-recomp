# Regenerates ../nvn_smoothcam_spv.h from smoothcam_depth.comp and smoothcam_warp.comp (glslangValidator from tools/vulkan_sdk).
# Run: python -I make_smoothcam_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_smoothcam_spv.py from shaders/smoothcam_*.comp (smooth camera). No game data.',
       '#pragma once', '#include <cstdint>', 'namespace nvn {']
for src, name in (('smoothcam_depth.comp', 'kScDepthSpv'), ('smoothcam_warp.comp', 'kScWarpSpv')):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', str(here / src), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        w = struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())
    out.append('static const uint32_t %s[] = {%s};' % (name, ','.join(hex(x) for x in w)))
out.append('}  // namespace nvn')
(here.parent / 'nvn_smoothcam_spv.h').write_text('\n'.join(out) + '\n')
