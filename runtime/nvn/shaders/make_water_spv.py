# Regenerates ../nvn_water_spv.h from water_fx.frag (glslangValidator from tools/vulkan_sdk). Run: python -I make_water_spv.py
# Two modules: kWaterFxFrag (plain) and kWaterFxRtFrag (-DRT_REFL=1: ray query reflections, only created when the ray tracing device is up).
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
g = here.parents[2] / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'


def build(defs):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '--target-env', 'vulkan1.3', '-S', 'frag', *defs, str(here / 'water_fx.frag'), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        return struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())


w, wr = build([]), build(['-DRT_REFL=1'])
(here.parent / 'nvn_water_spv.h').write_text('\n'.join(['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_water_spv.py from water_fx.frag (kWaterFxRtFrag: -DRT_REFL=1). Our own code, no game data.', '#pragma once', '#include <cstdint>',
    'static const uint32_t kWaterFxFrag[] = {' + ','.join(hex(x) for x in w) + '};',
    'static const uint32_t kWaterFxRtFrag[] = {' + ','.join(hex(x) for x in wr) + '};']) + '\n')
