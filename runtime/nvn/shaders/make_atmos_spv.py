# Regenerates ../nvn_atmos_spv.h from atmos_*.frag (glslangValidator from tools/vulkan_sdk). Run: python -I make_atmos_spv.py
# Each shader has a "//#include atmos_common" line that this script replaces by atmos_common.glsl before compiling.
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
common = (here / 'atmos_common.glsl').read_text()


def words(name):
    src = (here / name).read_text().replace('//#include atmos_common', common)
    with tempfile.TemporaryDirectory() as t:
        s = pathlib.Path(t) / 'in.frag'
        s.write_text(src)
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '-S', 'frag', str(s), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        return struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())


items = [('kAtmosDownFrag', 'atmos_down.frag'), ('kAtmosUpFrag', 'atmos_up.frag'), ('kAtmosStatsFrag', 'atmos_stats.frag'),
         ('kAtmosStateFrag', 'atmos_state.frag'), ('kAtmosShaftFrag', 'atmos_shaft.frag'), ('kAtmosCompFrag', 'atmos_comp.frag')]
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_atmos_spv.py from atmos_*.frag + atmos_common.glsl. Our own code, no game data.', '#pragma once', '#include <cstdint>']
for name, src in items:
    out.append(f'static const uint32_t {name}[] = {{' + ','.join(hex(x) for x in words(src)) + '};')
(here.parent / 'nvn_atmos_spv.h').write_text('\n'.join(out) + '\n')
print('wrote', here.parent / 'nvn_atmos_spv.h')
