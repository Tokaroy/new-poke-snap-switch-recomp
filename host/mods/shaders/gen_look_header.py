# Compiles look.vert / look.frag / look_state.frag with the Vulkan SDK's glslangValidator and writes host/mods/look_spv.h.
# Usage: tools\venv-recomp\Scripts\python -I host\mods\shaders\gen_look_header.py
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GLSLANG = ROOT / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
OUT = ROOT / 'host' / 'mods' / 'look_spv.h'


def compile_words(src):
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / 'o.spv'
        subprocess.run([str(GLSLANG), '-V', '--target-env', 'vulkan1.1', '-o', str(out), str(src)], check=True)
        d = out.read_bytes()
    return struct.unpack('<%dI' % (len(d) // 4), d)


def main():
    here = Path(__file__).parent
    parts = ['// Generated by host/mods/shaders/gen_look_header.py from look.vert / look.frag / look_state.frag. Do not edit.', '#pragma once', '#include <cstdint>']
    for name, f in (('kLook_vert', 'look.vert'), ('kLook_frag', 'look.frag'), ('kLookState_frag', 'look_state.frag')):
        w = compile_words(here / f)
        parts.append('static const uint32_t %s[] = {\n%s};' % (name, ',\n'.join(','.join('0x%08x' % x for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n'))
    OUT.write_text('\n'.join(parts) + '\n', newline='\n')
    print('wrote', OUT)


if __name__ == '__main__':
    sys.exit(main())
