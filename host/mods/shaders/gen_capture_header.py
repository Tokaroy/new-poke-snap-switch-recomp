# Compiles capture_lanczos.frag (two variants) with the Vulkan SDK's glslangValidator and writes runtime/nvn/nvn_capture_spv.h.
# Usage: tools\venv-recomp\Scripts\python -I host\mods\shaders\gen_capture_header.py
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GLSLANG = ROOT / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
SRC = Path(__file__).with_name('capture_lanczos.frag')
OUT = ROOT / 'runtime' / 'nvn' / 'nvn_capture_spv.h'


def compile_words(defines):
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / 'o.spv'
        subprocess.run([str(GLSLANG), '-V', '--target-env', 'vulkan1.1', *defines, '-o', str(out), str(SRC)], check=True)
        d = out.read_bytes()
    return struct.unpack('<%dI' % (len(d) // 4), d)


def main():
    parts = ['// Generated by host/mods/shaders/gen_capture_header.py from capture_lanczos.frag. Do not edit.',
             '#pragma once', '#include <cstdint>', '']
    for name, defs in (('k_caplz_srgb', ['-DCAPTURE']), ('k_caplz_plain', []), ('k_capone_srgb', ['-DCAPTURE', '-DSINGLE'])):
        w = compile_words(defs)
        parts.append('static const uint32_t %s[%d] = {%s};' % (name, len(w), ','.join(hex(x) for x in w)))
    OUT.write_text('\n'.join(parts) + '\n', newline='\n')
    print('wrote', OUT)


if __name__ == '__main__':
    sys.exit(main())
